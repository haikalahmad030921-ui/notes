class _GeoPathPainter extends CustomPainter {
  @override
  void paint(Canvas canvas, Size size) {
    final w = size.width;
    final h = size.height;

    final path = Path()
      ..moveTo(w * 0.98, h * 0.25)
      ..cubicTo(w * 0.55, h * 0.30, w * 0.38, h * 0.52, w * 0.42, h * 0.65)
      ..cubicTo(w * 0.46, h * 0.78, w * 0.85, h * 0.80, w * 0.80, h * 1.02);

    // Deep 3D shadow edge
    canvas.drawPath(
      path.shift(const Offset(10, 12)),
      Paint()
        ..color = const Color(0xFF1F126B).withValues(alpha: 0.55)
        ..style = PaintingStyle.stroke
        ..strokeWidth = 62
        ..strokeCap = StrokeCap.round,
    );

    // Main ribbon road
    canvas.drawPath(
      path,
      Paint()
        ..color = const Color(0xFF5D4EE0)
        ..style = PaintingStyle.stroke
        ..strokeWidth = 56
        ..strokeCap = StrokeCap.round,
    );

    // Subtle inner highlight
    canvas.drawPath(
      path,
      Paint()
        ..color = const Color(0xFF7B6DF0).withValues(alpha: 0.35)
        ..style = PaintingStyle.stroke
        ..strokeWidth = 44
        ..strokeCap = StrokeCap.round,
    );
  }

  @override
  bool shouldRepaint(covariant CustomPainter oldDelegate) => false;
}
